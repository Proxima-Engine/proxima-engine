//! Database adapter contract for the database-independent Proxima Security Core.
//!
//! A database driver is not an adapter by itself. An implementation must inspect
//! native authorization state, compile the canonical policy, verify effective
//! enforcement, and detect drift. No planned adapter is registered as supported.

use crate::security_core::{
    AdapterDescriptor, DatabaseKind, InspectionCompleteness, Operation, ProtectedResource,
    SecurityFinding, SecurityPosture, TenantSecurityPolicy, VerificationReport,
};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::{
    collections::HashMap,
    future::Future,
    pin::Pin,
    sync::Arc,
};

pub type AdapterFuture<'a, T> = Pin<Box<dyn Future<Output = T> + Send + 'a>>;

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdapterTarget {
    /// Stable, non-secret identifier for the configured database target.
    pub target_id: String,
    pub database_name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub namespace: Option<String>,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct InspectionRequest {
    pub target: AdapterTarget,
    pub policy: TenantSecurityPolicy,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ResourceInspection {
    pub resource: ProtectedResource,
    pub completeness: InspectionCompleteness,
    pub posture: SecurityPosture,
    /// Operations whose native enforcement was actually inspected and verified.
    pub verified_operations: Vec<Operation>,
    pub findings: Vec<SecurityFinding>,
    pub fingerprint: Option<String>,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct InspectionSnapshot {
    pub database_kind: DatabaseKind,
    pub target: AdapterTarget,
    pub completeness: InspectionCompleteness,
    pub posture: SecurityPosture,
    pub resources: Vec<ResourceInspection>,
    pub findings: Vec<SecurityFinding>,
    pub fingerprint: Option<String>,
    /// RFC 3339 timestamp generated by the adapter after inspection completes.
    pub observed_at: String,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativePolicyChange {
    pub resource: ProtectedResource,
    /// Adapter-defined operation such as create_policy or update_role_binding.
    pub action: String,
    /// Native, reviewable definition. It is never executed by policy compilation.
    pub definition: Value,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CompiledPolicy {
    pub database_kind: DatabaseKind,
    pub policy_id: String,
    pub revision: u64,
    pub changes: Vec<NativePolicyChange>,
    /// Applying native changes requires a separately authorized approval step.
    pub requires_approval: bool,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DriftReport {
    pub database_kind: DatabaseKind,
    pub target: AdapterTarget,
    pub detected: bool,
    pub completeness: InspectionCompleteness,
    pub previous_fingerprint: Option<String>,
    pub observed_fingerprint: Option<String>,
    pub findings: Vec<SecurityFinding>,
    pub observed_at: String,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdapterError {
    pub code: String,
    pub detail: String,
    pub retryable: bool,
}

impl std::fmt::Display for AdapterError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "{}: {}", self.code, self.detail)
    }
}

impl std::error::Error for AdapterError {}

/// Native database adapter boundary. Implementations must fail closed when
/// inspection is incomplete and must never claim verification from a connection
/// test, catalog listing, or generated policy alone.
pub trait DatabaseAdapter: Send + Sync {
    fn descriptor(&self) -> AdapterDescriptor;

    fn inspect<'a>(
        &'a self,
        request: &'a InspectionRequest,
    ) -> AdapterFuture<'a, Result<InspectionSnapshot, AdapterError>>;

    fn compile_policy(
        &self,
        policy: &TenantSecurityPolicy,
    ) -> Result<CompiledPolicy, AdapterError>;

    fn verify<'a>(
        &'a self,
        policy: &'a TenantSecurityPolicy,
        snapshot: &'a InspectionSnapshot,
    ) -> AdapterFuture<'a, Result<VerificationReport, AdapterError>>;

    fn detect_drift<'a>(
        &'a self,
        target: &'a AdapterTarget,
        previous_fingerprint: Option<&'a str>,
    ) -> AdapterFuture<'a, Result<DriftReport, AdapterError>>;
}

#[derive(Default)]
pub struct AdapterRegistry {
    adapters: HashMap<DatabaseKind, Arc<dyn DatabaseAdapter>>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RegistryError {
    DuplicateAdapter,
    IncompleteAdapter,
}

impl AdapterRegistry {
    pub fn register(&mut self, adapter: Arc<dyn DatabaseAdapter>) -> Result<(), RegistryError> {
        let descriptor = adapter.descriptor();
        if descriptor.maturity != crate::security_core::AdapterMaturity::Supported
            || !descriptor.capabilities.is_production_complete()
        {
            return Err(RegistryError::IncompleteAdapter);
        }
        let kind = descriptor.kind;
        if self.adapters.contains_key(&kind) {
            return Err(RegistryError::DuplicateAdapter);
        }
        self.adapters.insert(kind, adapter);
        Ok(())
    }

    pub fn get(&self, kind: DatabaseKind) -> Option<Arc<dyn DatabaseAdapter>> {
        self.adapters.get(&kind).cloned()
    }

    pub fn registered_kinds(&self) -> Vec<DatabaseKind> {
        let mut kinds: Vec<_> = self.adapters.keys().copied().collect();
        kinds.sort_by_key(|kind| format!("{kind:?}"));
        kinds
    }

    pub fn descriptors(&self) -> Vec<AdapterDescriptor> {
        let mut descriptors: Vec<_> = self.adapters.values().map(|adapter| adapter.descriptor()).collect();
        descriptors.sort_by_key(|descriptor| format!("{:?}", descriptor.kind));
        descriptors
    }
}


#[cfg(test)]
mod registry_tests {
    use super::*;
    use crate::security_core::{AdapterCapabilities, AdapterMaturity};

    struct CandidateAdapter {
        maturity: AdapterMaturity,
        capabilities: AdapterCapabilities,
    }

    impl DatabaseAdapter for CandidateAdapter {
        fn descriptor(&self) -> AdapterDescriptor {
            AdapterDescriptor {
                kind: DatabaseKind::MySql,
                name: "candidate",
                maturity: self.maturity,
                capabilities: self.capabilities,
                status_note: "test adapter",
            }
        }

        fn inspect<'a>(&'a self, _request: &'a InspectionRequest) -> AdapterFuture<'a, Result<InspectionSnapshot, AdapterError>> {
            Box::pin(async { Err(AdapterError { code: "not_implemented".into(), detail: "test adapter".into(), retryable: false }) })
        }

        fn compile_policy(&self, _policy: &TenantSecurityPolicy) -> Result<CompiledPolicy, AdapterError> {
            Err(AdapterError { code: "not_implemented".into(), detail: "test adapter".into(), retryable: false })
        }

        fn verify<'a>(&'a self, _policy: &'a TenantSecurityPolicy, _snapshot: &'a InspectionSnapshot) -> AdapterFuture<'a, Result<VerificationReport, AdapterError>> {
            Box::pin(async { Err(AdapterError { code: "not_implemented".into(), detail: "test adapter".into(), retryable: false }) })
        }

        fn detect_drift<'a>(&'a self, _target: &'a AdapterTarget, _previous_fingerprint: Option<&'a str>) -> AdapterFuture<'a, Result<DriftReport, AdapterError>> {
            Box::pin(async { Err(AdapterError { code: "not_implemented".into(), detail: "test adapter".into(), retryable: false }) })
        }
    }

    #[test]
    fn registry_rejects_review_only_and_partial_adapters() {
        let adapter = CandidateAdapter {
            maturity: AdapterMaturity::InDevelopment,
            capabilities: AdapterCapabilities { policy_generation: true, ..AdapterCapabilities::default() },
        };
        let mut registry = AdapterRegistry::default();
        assert_eq!(registry.register(Arc::new(adapter)).unwrap_err(), RegistryError::IncompleteAdapter);
        assert!(registry.get(DatabaseKind::MySql).is_none());
    }

    #[test]
    fn registry_accepts_only_a_complete_supported_adapter() {
        let adapter = CandidateAdapter {
            maturity: AdapterMaturity::Supported,
            capabilities: AdapterCapabilities {
                schema_inspection: true,
                tenant_identity_enforcement: true,
                policy_semantic_verification: true,
                policy_generation: true,
                controlled_policy_deployment: true,
                drift_detection: true,
                runtime_fail_closed_admission: true,
                signed_security_evidence: true,
            },
        };
        let mut registry = AdapterRegistry::default();
        assert!(registry.register(Arc::new(adapter)).is_ok());
        assert!(registry.get(DatabaseKind::MySql).is_some());
    }
}
